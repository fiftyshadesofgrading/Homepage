// build-turkey.mjs: turn the CSVs from queries.sql into what the post needs.
//   1. assets/posts/wild-turkey-comeback/turkey-map-data.js  (state outlines + projected routes, for the map)
//   2. assets/posts/wild-turkey-comeback/turkey.db           (SQLite, for Datasette Lite)
//
// Usage, from the repo root, with the CSVs in tools/turkey/out/:
//   npm i --no-save us-atlas topojson-client d3-geo
//   node tools/turkey/build-turkey.mjs tools/turkey/out
// Needs Node 22+ (node:sqlite is built in).
import fs from 'node:fs';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { feature, mesh } from 'topojson-client';
import { geoAlbersUsa, geoPath } from 'd3-geo';

const IN = process.argv[2] || 'tools/turkey/out';
const OUT = 'assets/posts/wild-turkey-comeback';
fs.mkdirSync(OUT, { recursive: true });

const readCsv = (f) => {
  const [head, ...lines] = fs.readFileSync(path.join(IN, f), 'utf8').trim().split(/\r?\n/);
  const cols = head.split(',');
  return lines.map((l) => {
    const out = {}; let cur = '', q = false, i = 0;
    for (const ch of l) {
      if (ch === '"') q = !q;
      else if (ch === ',' && !q) { out[cols[i++]] = cur; cur = ''; }
      else cur += ch;
    }
    out[cols[i]] = cur; return out;
  });
};
const num = (v) => (v === '' ? null : +v);

// ---------- 1. map data ----------
const topo = JSON.parse(fs.readFileSync(new URL(import.meta.resolve('us-atlas/states-albers-10m.json'))));
const keep = { ...topo.objects.states, geometries: topo.objects.states.geometries.filter((g) => !['02', '15'].includes(String(g.id))) };
const gp = geoPath(null);
const lower48 = feature(topo, keep);
const land = gp(lower48), borders = gp(mesh(topo, keep, (a, b) => a !== b));
const [[x0, y0], [x1, y1]] = gp.bounds(lower48);
const viewBox = [x0 - 8, y0 - 8, x1 - x0 + 16, y1 - y0 + 16].map(Math.round);
const proj = geoAlbersUsa().scale(1300).translate([487.5, 305]);   // the projection us-atlas used

const DECADES = [1960, 1970, 1980, 1990, 2000, 2010, 2020];
const routes = new Map();
for (const r of readCsv('turkey_route_decade.csv')) {
  if (r.state_name === 'Alaska' || r.state_name === 'Hawaii') continue;
  const xy = proj([+r.longitude, +r.latitude]);
  if (!xy) continue;
  if (!routes.has(r.route_id)) routes.set(r.route_id, { xy, name: r.route_name, state: r.state_name, d: DECADES.map(() => null) });
  routes.get(r.route_id).d[DECADES.indexOf(+r.decade)] = +r.turkeys_per_run;
}
const yearly = readCsv('turkey_us_yearly.csv').map((r) => [+r.year, +r.routes_run, +r.pct_routes_with_turkeys, +r.turkeys_per_route]);
const states = readCsv('turkey_state_change.csv').map((r) => [r.state_name, num(r.pct_1970s), num(r.pct_recent), +r.routes_recent]);
const title = (s) => s.toLowerCase().replace(/\b\w/g, (c) => c.toUpperCase());
fs.writeFileSync(path.join(OUT, 'turkey-map-data.js'),
  '// generated by tools/turkey/build-turkey.mjs from the USGS Breeding Bird Survey - do not edit\n' +
  'window.TURKEY = ' + JSON.stringify({
    viewBox, land, borders, decades: DECADES,
    routeFields: ['x', 'y', 'name', 'state', 'perDecade'],
    routes: [...routes.values()].map((r) => [+r.xy[0].toFixed(1), +r.xy[1].toFixed(1), title(r.name), r.state, r.d]),
    yearFields: ['year', 'routesRun', 'pctWithTurkeys', 'turkeysPerRoute'], yearly,
    stateFields: ['state', 'pct1970s', 'pctRecent', 'routesRecent'], states,
  }) + ';\n');
console.log(`map: ${routes.size} routes, ${yearly.length} years, ${states.length} states`);

// ---------- 2. SQLite for Datasette Lite ----------
const dbPath = path.join(OUT, 'turkey.db');
fs.rmSync(dbPath, { force: true });
const db = new DatabaseSync(dbPath);
db.exec(`
  CREATE TABLE routes (id INTEGER PRIMARY KEY, route_name TEXT, route_code TEXT, country TEXT, state TEXT, latitude REAL, longitude REAL);
  CREATE TABLE turkey_runs (route INTEGER REFERENCES routes(id), year INTEGER, turkeys INTEGER, PRIMARY KEY (route, year)) WITHOUT ROWID;
  CREATE TABLE us_yearly (year INTEGER PRIMARY KEY, routes_run INTEGER, routes_with_turkeys INTEGER, pct_routes_with_turkeys REAL, turkeys_per_route REAL);
  CREATE TABLE state_change (state TEXT PRIMARY KEY, pct_1970s REAL, pct_recent REAL, routes_recent INTEGER);
`);
const insR = db.prepare('INSERT INTO routes VALUES (?,?,?,?,?,?,?)');
const ids = new Map();   // route code -> small integer id (keeps the file small)
const insT = db.prepare('INSERT INTO turkey_runs VALUES (?,?,?)');
db.exec('BEGIN');
for (const r of readCsv('turkey_runs.csv')) {
  if (!ids.has(r.route_id)) {
    ids.set(r.route_id, ids.size + 1);
    insR.run(ids.size, title(r.route_name), r.route_id, r.country_num === '840' ? 'US' : r.country_num === '124' ? 'Canada' : 'Mexico', r.state_name || null, +r.latitude, +r.longitude);
  }
  insT.run(ids.get(r.route_id), +r.year, +r.turkeys);
}
const insY = db.prepare('INSERT INTO us_yearly VALUES (?,?,?,?,?)');
for (const r of readCsv('turkey_us_yearly.csv')) insY.run(+r.year, +r.routes_run, +r.routes_with_turkeys, +r.pct_routes_with_turkeys, +r.turkeys_per_route);
const insS = db.prepare('INSERT INTO state_change VALUES (?,?,?,?)');
for (const r of readCsv('turkey_state_change.csv')) insS.run(r.state_name, num(r.pct_1970s), num(r.pct_recent), +r.routes_recent);
db.exec('COMMIT; VACUUM;');
db.close();
console.log(`db: ${(fs.statSync(dbPath).size / 1e6).toFixed(1)} MB`);
